    #[test]
    fn an_unreadable_cache_reads_as_empty_without_an_error() {
        let temp = tempfile::tempdir().expect("tempdir");
        std::fs::create_dir_all(temp.path().join(".rr")).expect("state dir");
        std::fs::write(temp.path().join(ROUTES_PATH), b"not a routes file\n").expect("write");

        let (table, fault) = load_routes(temp.path());
        assert!(table.is_empty());
        assert_eq!(fault, Some(RouteFault::Frontmatter));

        std::fs::write(temp.path().join(ROUTES_PATH), [0xFF, 0xFE]).expect("write");
        let (table, fault) = load_routes(temp.path());
        assert!(table.is_empty());
        assert_eq!(fault, Some(RouteFault::NotUtf8));
    }

