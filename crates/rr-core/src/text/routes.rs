    #[test]
    fn eviction_drops_the_least_believed_route() {
        let mut table = RouteTable::default();
        for index in 0..=MAX_ROUTES {
            let step = u16::try_from(index).expect("the fixture stays under 65536 routes");
            let confidence = 0.1 + f32::from(step) / f32::from(u16::MAX);
            table.insert(record(
                &format!("question{index}"),
                "src/auth/token.rs#verify_token",
                confidence,
            ));
        }
        assert_eq!(table.len(), MAX_ROUTES);
        assert!(
            table.get(&RouteKey::new("question0").unwrap()).is_none(),
            "the least-believed record survived eviction"
        );
        assert!(
            table
                .get(&RouteKey::new(&format!("question{MAX_ROUTES}")).unwrap())
                .is_some(),
            "the most-believed record was evicted"
        );
    }

    /// No clock and no counter, so the same overflow evicts the same record
    /// every time — which is what lets the golden test be a golden test.
    #[test]
    fn eviction_is_deterministic_across_equal_confidences() {
        let build = || {
            let mut table = RouteTable::default();
            for index in 0..=MAX_ROUTES {
                table.insert(record(
                    &format!("question{index}"),
                    "src/auth/token.rs#verify_token",
                    0.5,
                ));
            }
            table
        };
        let first = build();
        let second = build();
        assert_eq!(
            render_routes(&first).expect("render"),
            render_routes(&second).expect("render")
        );
        assert_eq!(first.len(), MAX_ROUTES);
    }

